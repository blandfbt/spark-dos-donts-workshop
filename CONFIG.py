# DBTITLE 1,Check your schema and make it the default
# Instructor setup notebooks set INSTRUCTOR_SETUP = True before running CONFIG: they write to SOURCE_SCHEMA
# and don't need a USER_SCHEMA.
if not globals().get("INSTRUCTOR_SETUP", False):
    if not USER_SCHEMA:
        raise ValueError(
            f"USER_SCHEMA is empty. Open CONFIG (at the top of the repo) and set USER_SCHEMA = "
            f"\"{suggested_user_schema()}\" (your firstname_lastname schema in {CATALOG}), then rerun this cell."
        )
    # Only the instructor's prebuild (instructor_setup/01_prebuild_shared_gold) runs the lab into the shared schema.
    if USER_SCHEMA == SOURCE_SCHEMA and _job_param("allow_source_schema_writes", "false") != "true":
        raise ValueError(f"USER_SCHEMA can't be the shared source schema '{SOURCE_SCHEMA}'. Use your own schema.")
    try:
        spark.sql(f"DESCRIBE SCHEMA `{CATALOG}`.`{USER_SCHEMA}`")
    except Exception:
        raise ValueError(
            f"Schema {CATALOG}.{USER_SCHEMA} doesn't exist or you can't see it. Check the spelling in CONFIG, "
            f"or ask your instructor to create it (instructor_setup/02_create_participant_schemas)."
        )
    spark.sql(f"CREATE VOLUME IF NOT EXISTS `{CATALOG}`.`{USER_SCHEMA}`.`scratch_files`")
    # Short table names in SQL cells (lab_..., sdd_scratch_...) now mean *your* schema.
    spark.sql(f"USE CATALOG `{CATALOG}`")
    spark.sql(f"USE SCHEMA `{USER_SCHEMA}`")
    print(f"📥 source data (read-only): {CATALOG}.{SOURCE_SCHEMA}   raw files: {SOURCE_VOLUME}")
    print(f"📤 your schema:             {CATALOG}.{USER_SCHEMA}   scratch files: {USER_VOLUME}")
