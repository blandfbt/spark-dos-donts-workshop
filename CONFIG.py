# Jobs (the instructor's bundle) can override the three settings above with job parameters of the same name.
# instructor_setup/01_prebuild_shared_gold sets PREBUILD_OVERRIDES before it %runs the lab (a %run can't pass
# parameters on to the notebooks the lab includes). Opened by hand, neither exists and the values above are used.
def _job_param(name, default):
    overrides = globals().get("PREBUILD_OVERRIDES") or {}
    if name in overrides:
        return str(overrides[name])
    try:
        return dbutils.widgets.get(name).strip() or default
    except Exception:
        return default


CATALOG = _job_param("catalog", CATALOG)
SOURCE_SCHEMA = _job_param("source_schema", SOURCE_SCHEMA)
USER_SCHEMA = _job_param("user_schema", USER_SCHEMA).strip()

WORKSHOP_TAG_KEY = "workshop_name"  # same key as the bundle's presets.tags
WORKSHOP_TAG = _job_param("workshop_tag", "spark_dos_donts")

CURRENT_USER = spark.sql("SELECT current_user()").first()[0]

SOURCE_VOLUME = f"/Volumes/{CATALOG}/{SOURCE_SCHEMA}/raw_files"      # raw files generated by the instructor (read-only)
USER_VOLUME = f"/Volumes/{CATALOG}/{USER_SCHEMA}/scratch_files"      # your checkpoints and landing files
VOLUME = SOURCE_VOLUME                                               # older name, kept for the notebooks' raw-file reads


def SRC(name):
    """Fully qualified name of a shared source table (read-only): dbx_workshop_dev.shared.<name>."""
    return f"`{CATALOG}`.`{SOURCE_SCHEMA}`.`{name}`"


def T(name):
    """Fully qualified name of a table in your own schema: dbx_workshop_dev.<USER_SCHEMA>.<name>."""
    return f"`{CATALOG}`.`{USER_SCHEMA}`.`{name}`"


def suggested_user_schema(user=None):
    """firstname_lastname from an email such as jane.doe@company.com."""
    local = (user or CURRENT_USER).split("@")[0].lower()
    return re.sub(r"_+", "_", re.sub(r"[^a-z0-9]", "_", local)).strip("_")


def tag_workshop_objects(schema=None, value=None):
    """Tag a schema, its volumes and its tables with workshop_name (for easy filtering). Never a blocker."""
    schema, value = schema or USER_SCHEMA, value or WORKSHOP_TAG
    tagged, skipped = 0, []
    targets = [("SCHEMA", f"`{CATALOG}`.`{schema}`")]
    targets += [("VOLUME", f"`{CATALOG}`.`{schema}`.`{v.volume_name}`")
                for v in spark.sql(f"SHOW VOLUMES IN `{CATALOG}`.`{schema}`").collect()]
    targets += [("TABLE", f"`{CATALOG}`.`{schema}`.`{t.tableName}`")
                for t in spark.sql(f"SHOW TABLES IN `{CATALOG}`.`{schema}`").where("NOT isTemporary").collect()]
    for kind, name in targets:
        try:
            spark.sql(f"ALTER {kind} {name} SET TAGS ('{WORKSHOP_TAG_KEY}' = '{value}')")
            tagged += 1
        except Exception as e:  # e.g. missing APPLY TAG privilege
            skipped.append(f"{name}: {str(e).strip().splitlines()[0][:80]}")
    print(f"🏷️  tagged {tagged} objects with {WORKSHOP_TAG_KEY} = {value}" + (f" ({len(skipped)} skipped)" if skipped else ""))
    for s in skipped[:3]:
        print("   ", s)


